def format_history():
    """渲染更新记录为纯文本（最新在前）。"""
    parts = []
    for v in VERSION_HISTORY:
        parts.append(f"【v{v['version']}】{v['date']}")
        for ch in v["changes"]:
            parts.append(f"  · {ch}")
        parts.append("")
    return "\n".join(parts)

