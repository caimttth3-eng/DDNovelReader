def set_lang(lang):
    global _LANG
    _LANG = lang if lang in ("en", "ja", "ko", "zh") else "zh"


def get_lang():
    return _LANG


def detect_system_lang():
    """检测系统默认界面语言，返回 zh / en / ja / ko；四种以外的系统默认用英语。"""
    import os as _os
    code = None
    try:
        if _os.name == "nt":
            import ctypes
            lid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            prim = lid & 0x3FF
            code = {4: "zh", 9: "en", 17: "ja", 18: "ko"}.get(prim, "en")
        else:
            import locale
            loc = (locale.getdefaultlocale() or (None, None))[0] or ""
            loc = loc.lower()
            if loc.startswith("zh"):
                code = "zh"
            elif loc.startswith("ja"):
                code = "ja"
            elif loc.startswith("ko"):
                code = "ko"
            else:
                code = "en"
    except Exception:
        code = "en"
    return code if code in ("zh", "en", "ja", "ko") else "en"


